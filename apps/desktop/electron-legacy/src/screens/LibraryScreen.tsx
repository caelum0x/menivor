import { useCallback, useEffect, useState } from "react";

import { listJobs } from "../lib/api";
import type { Job } from "../lib/types";
import { JobState } from "../lib/types";

/** Human label + badge modifier for a job state. */
function stateMeta(state: number): { label: string; cls: string } {
  switch (state) {
    case JobState.Complete:
      return { label: "Complete", cls: "badge--ok" };
    case JobState.Failed:
      return { label: "Failed", cls: "badge--fail" };
    case JobState.Processing:
      return { label: "Processing", cls: "badge--run" };
    default:
      return { label: `State ${state}`, cls: "badge--run" };
  }
}

interface LibraryScreenProps {
  /** Jump to the Create screen (empty-state CTA). */
  onCreate: () => void;
}

/**
 * Library screen: a grid of every reel generated by this account
 * (GET /jobs, newest-first as the backend returns them). Completed reels play
 * inline and can be opened/downloaded; in-flight jobs show their status.
 */
export function LibraryScreen({ onCreate }: LibraryScreenProps) {
  const [jobs, setJobs] = useState<Job[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      setJobs(await listJobs());
    } catch (err) {
      setError(err instanceof Error ? err.message : "Could not load your reels.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  return (
    <section className="view">
      <div className="view-head view-head--row">
        <div>
          <h1 className="view-title">Your reels</h1>
          <p className="view-sub">
            Every reel you have generated from this account.
          </p>
        </div>
        <button
          type="button"
          className="btn btn--ghost"
          onClick={() => void load()}
          disabled={loading}
        >
          {loading ? "Refreshing…" : "Refresh"}
        </button>
      </div>

      {error && <p className="error-text">{error}</p>}

      {loading && jobs.length === 0 && (
        <div className="card panel empty">
          <p className="muted">Loading your reels…</p>
        </div>
      )}

      {!loading && jobs.length === 0 && !error && (
        <div className="card panel empty">
          <p className="muted">No reels yet. Record a screen capture to get started.</p>
          <button type="button" className="btn btn--primary" onClick={onCreate}>
            Create your first reel
          </button>
        </div>
      )}

      {jobs.length > 0 && (
        <div className="reel-grid">
          {jobs.map((job) => {
            const meta = stateMeta(job.state);
            const pct = Math.round((job.progress ?? 0) * 100);
            const inFlight = job.state === JobState.Processing;
            return (
              <article key={job.job_id} className="card reel-card">
                <div className="reel-thumb">
                  {job.result_url ? (
                    <video
                      className="reel-video"
                      src={job.result_url}
                      controls
                      preload="metadata"
                    />
                  ) : (
                    <div className="reel-placeholder">
                      <span className="muted">{meta.label}</span>
                      {inFlight && (
                        <div className="progress reel-progress">
                          <div
                            className="progress-bar"
                            style={{ width: `${pct}%` }}
                          />
                        </div>
                      )}
                    </div>
                  )}
                </div>
                <div className="reel-meta">
                  <span className={`badge ${meta.cls}`}>{meta.label}</span>
                  <span className="reel-id" title={job.job_id}>
                    {job.job_id}
                  </span>
                </div>
                {job.result_url && (
                  <div className="reel-actions">
                    <a
                      className="btn btn--ghost btn--sm"
                      href={job.result_url}
                      target="_blank"
                      rel="noreferrer"
                    >
                      Open / download
                    </a>
                  </div>
                )}
                {job.state === JobState.Failed && job.error && (
                  <p className="error-text small reel-error">{job.error}</p>
                )}
              </article>
            );
          })}
        </div>
      )}
    </section>
  );
}
